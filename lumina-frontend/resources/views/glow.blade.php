            <h3>Sunscreen</h3>
            <p>Sunscreen is a non-negotiable step in your skincare routine — apply it every day, even if you’re staying indoors, because UV rays can still pass through windows. Be generous with the amount; about two fingers’ length is recommended for full coverage of the face and neck. If you’re outdoors or sweating, make sure to reapply every 2–3 hours.</p>
