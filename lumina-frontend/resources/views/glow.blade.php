            <p>Serum should be used before your moisturizer to deliver concentrated ingredients directly into your skin. You only need 2–3 drops for your whole face, so a little goes a long way. Instead of rubbing it in, gently press the serum into your skin to help it absorb better and reduce irritation.</p>
